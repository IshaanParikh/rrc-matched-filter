#!/usr/bin/env python3
"""
at-speed self-test of the DueProLogic build (hw_demo/dpl/rrc_bist.v).

host trigger bit 1 starts it: the board clears the filter, pushes one
LFSR sample into it on every 66 MHz clock for 2^20 clocks, CRCs every
output, and sends back a 9-word report over the same link dpl_host.py uses.
this script computes the same report from the bit-exact model and compares.

    python python/dpl_bist.py --port COM14              # one run
    python python/dpl_bist.py --port COM14 --runs 100   # 100 runs, ~10 s
    python python/dpl_bist.py --model-only              # print what to expect

report words, each sent low byte first like a filter output:
    0xB157 magic, crc lo, crc hi, n_out lo, n_out hi, cycles lo, cycles hi,
    n_sat lo, n_sat hi

run from repo root.
"""

import argparse
import os
import sys
import time
import zlib

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dsp_common import Q_FRAC_BITS, read_hex, round_sat  # noqa: E402
from golden_model import golden_fir  # noqa: E402

MAGIC = 0xB157
SEED = 0xACE12025
MASK = 0x80200003
BOOTH_LATENCY = 4           # rtl/rrc_defs.vh BOOTH_R4_LATENCY
CMD_TRIGGER = 0x1
CMD_TRANSFER = 0x2


def lfsr_samples(n, seed=SEED):
    """Galois right-shift LFSR, 16 shifts per sample, sample = state[31:16]"""
    s = seed
    out = np.empty(n, dtype=np.int64)
    for k in range(n):
        for _ in range(16):
            s = (s >> 1) ^ MASK if s & 1 else s >> 1
        v = s >> 16
        out[k] = v - 0x10000 if v & 0x8000 else v
    return out


def latency(n_taps):
    return 1 + BOOTH_LATENCY + int(np.ceil(np.log2(n_taps))) + 1


def model(coeff, len_log2=20, seed=SEED):
    x = lfsr_samples(1 << len_log2, seed)
    y = round_sat(golden_fir(x, coeff), Q_FRAC_BITS, 16).astype(np.int64)
    crc = zlib.crc32((y & 0xFFFF).astype("<u2").tobytes()) & 0xFFFFFFFF
    n_sat = int(np.count_nonzero((y == 32767) | (y == -32768)))
    return dict(crc=crc, n_out=y.size, cycles=y.size + latency(coeff.size), n_sat=n_sat)


def words_of(r):
    w = [MAGIC]
    for key in ("crc", "n_out", "cycles", "n_sat"):
        w += [r[key] & 0xFFFF, (r[key] >> 16) & 0xFFFF]
    return w


def parse(words):
    if words[0] != MAGIC:
        return None
    vals = [words[i] | (words[i + 1] << 16) for i in range(1, 9, 2)]
    return dict(zip(("crc", "n_out", "cycles", "n_sat"), vals))


def main(argv=None):
    ap = argparse.ArgumentParser(description="At-speed self-test of the DueProLogic RRC filter.")
    ap.add_argument("--port", help="FT2232H UART port, e.g. COM14")
    ap.add_argument("--baud", type=int, default=115200)
    ap.add_argument("--coeffs", default="hw_demo/data/rrc_coeffs.hex")
    ap.add_argument("--addr", type=int, default=1, help="SAMPLE_ADDR in dpl_top.v")
    ap.add_argument("--len-log2", type=int, default=20, help="BIST_LEN_LOG2 in dpl_top.v")
    ap.add_argument("--runs", type=int, default=1)
    ap.add_argument("--timeout", type=float, default=2.0)
    ap.add_argument("--model-only", action="store_true")
    ap.add_argument("--write-vh", default=None,
                    help="write the expected report as Verilog defines (for the testbench)")
    args = ap.parse_args(argv)

    coeff, _ = read_hex(args.coeffs, 16, signed=True)
    t0 = time.time()
    exp = model(coeff, args.len_log2)
    n = 1 << args.len_log2
    print("model: %d samples, %d taps, %.1f s" % (n, coeff.size, time.time() - t0))
    print("  crc    %08x" % exp["crc"])
    print("  n_out  %d" % exp["n_out"])
    print("  cycles %d  (%d samples + %d latency, i.e. no gaps)"
          % (exp["cycles"], n, latency(coeff.size)))
    print("  n_sat  %d  (%.2f%% of outputs on a rail)" % (exp["n_sat"], 100.0 * exp["n_sat"] / n))

    if args.write_vh:
        with open(args.write_vh, "w", newline="\n") as fh:
            fh.write("// Generated by python/dpl_bist.py, do not edit by hand.\n")
            fh.write("`define BIST_EXP_LEN_LOG2 %d\n" % args.len_log2)
            for key in ("crc", "n_out", "cycles", "n_sat"):
                fh.write("`define BIST_EXP_%s 32'h%08x\n" % (key.upper(), exp[key]))
        print("  wrote %s" % args.write_vh)
    if args.model_only or not args.port:
        return 0

    import serial  # pyserial, only needed here

    reply_hdr = 0xC0 | (CMD_TRANSFER << 3) | args.addr
    n_fail = 0
    with serial.Serial(args.port, args.baud, timeout=args.timeout) as port:
        for run in range(args.runs):
            port.reset_input_buffer()
            t_run = time.time()
            port.write(bytes([0x80 | (CMD_TRIGGER << 3), 0x02]))   # trigger bit 1
            port.flush()
            raw = port.read(36)
            dt = time.time() - t_run
            if len(raw) < 36:
                print("run %d: timed out, got %d of 36 bytes" % (run, len(raw)))
                n_fail += 1
                break
            frames = [raw[i:i + 2] for i in range(0, 36, 2)]
            if any(f[0] != reply_hdr for f in frames):
                print("run %d: bad frame header: %s" % (run, raw.hex()))
                n_fail += 1
                break
            words = [frames[i][1] | (frames[i + 1][1] << 8) for i in range(0, 18, 2)]
            got = parse(words)
            ok = got == exp
            if not ok:
                n_fail += 1
            if not ok or args.runs <= 3 or run == args.runs - 1:
                print("run %d: %s in %.0f ms" % (run, "PASS" if ok else "FAIL", 1e3 * dt))
                if got is None:
                    print("  no magic word: %s" % " ".join("%04x" % w for w in words))
                else:
                    for key in ("crc", "n_out", "cycles", "n_sat"):
                        print("  %-6s board %10d  model %10d  %s"
                              % (key, got[key], exp[key], "" if got[key] == exp[key] else "<--"))
    total = args.runs * n
    print("%d of %d runs failed, %d samples checked back to back at the board clock -> %s"
          % (n_fail, args.runs, total, "PASS" if n_fail == 0 else "FAIL"))
    return 0 if n_fail == 0 else 1


if __name__ == "__main__":
    sys.exit(main())
